"""Output settings: the answer's format, length and language for one chat. Auto leaves it to the model.

Interactive answers are the owner's choice for every chat (`chats.interactive_answers` in the owner
settings document): when they apply, the turn is taught the catalog of parts Conker's dashboard can
draw from an ```openui block. The answer itself stays plain text in history, so later turns read
what the model wrote.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Literal

from pydantic import Field

from pi.core.errors import ServiceError
from pi.core.models import Strict
from pi.models.providers import Message
from pi.owner import settings as owner_settings

AUTO = {"format": "auto", "length": "auto", "language": "auto"}
# "auto" or a BCP 47 tag such as "ru" or "en-GB".
LANGUAGE = r"^(auto|[a-z]{2,3}(-[A-Za-z0-9]{2,8}){0,3})$"
FORMATS = {
    "text": "plain prose",
    "list": "a list",
    "table": "a table",
    "document": "a structured document with headings",
    "code": "code, with only brief explanation",
    "json": "only valid JSON",
}
LENGTHS = {
    "short": "short, a few sentences",
    "medium": "medium, a few paragraphs",
    "long": "long and thorough",
}
INTERACTIVE_SETTING = "chats.interactive_answers"
INTERACTIVE = ("auto", "on", "off")
# Generated by Conker's dashboard from the components it renders (npm run answer-ui:prompt) and
# pinned here; Conker's CI fails when the two differ.
CATALOG = Path(__file__).with_name("interactive_answers.txt").read_text(encoding="utf-8").strip()
# Hosted model providers, by the adapter names configured models use as `providerId`. Auto keeps
# interactive answers to these, which follow the catalog; a small local model (Ollama) or a provider
# not listed here gets plain Markdown.
HOSTED_PROVIDERS = frozenset({"anthropic", "chatgpt", "claude-code", "openai", "openrouter"})


class Output(Strict):
    format: Literal["auto", "text", "list", "table", "document", "code", "json"] = "auto"
    length: Literal["auto", "short", "medium", "long"] = "auto"
    language: str = Field(default="auto", max_length=35, pattern=LANGUAGE)


class Update(Strict):
    expected_revision: int = Field(ge=0)
    output: Output


class OutputError(ServiceError):
    pass


SCHEMA = """
CREATE TABLE IF NOT EXISTS session_output (
 session_id TEXT PRIMARY KEY REFERENCES sessions(id), revision INTEGER NOT NULL, output TEXT NOT NULL
);
CREATE TRIGGER IF NOT EXISTS inherit_session_output AFTER INSERT ON sessions
WHEN NEW.parent_id IS NOT NULL
BEGIN
 INSERT INTO session_output SELECT NEW.id,revision,output FROM session_output WHERE session_id=NEW.parent_id;
END;
"""


def _session(db, session_id):
    row = db.execute("SELECT status FROM sessions WHERE id=?", (session_id,)).fetchone()
    if (
        row is None
        or row["status"] == "forgotten"
        or db.execute(
            "SELECT 1 FROM forgotten_sessions WHERE session_id=?", (session_id,)
        ).fetchone()
    ):
        raise OutputError("not_found", "Conversation unavailable.", 404)
    return row["status"]


def _stored(db, session_id):
    row = db.execute(
        "SELECT revision,output FROM session_output WHERE session_id=?", (session_id,)
    ).fetchone()
    return (row["revision"], json.loads(row["output"])) if row else (0, dict(AUTO))


def load(store, session_id) -> dict:
    with store._connect() as db:
        _session(db, session_id)
        revision, output = _stored(db, session_id)
    return {"revision": revision, "output": output}


def save(store, session_id, body: Update) -> dict:
    body = Update.model_validate(body.model_dump())
    with store._connect() as db:
        db.execute("BEGIN IMMEDIATE")
        if _session(db, session_id) != "open":
            raise OutputError("session_closed", "Change output settings on an open chat.", 409)
        revision, _ = _stored(db, session_id)
        if revision != body.expected_revision:
            raise OutputError(
                "revision_conflict", "Output settings changed; reload before saving.", 409
            )
        db.execute(
            "INSERT INTO session_output VALUES (?,?,?) ON CONFLICT(session_id) "
            "DO UPDATE SET revision=excluded.revision,output=excluded.output",
            (session_id, revision + 1, body.output.model_dump_json()),
        )
        db.commit()
    return {"revision": revision + 1, "output": body.output.model_dump()}


def snapshot(db, session_id) -> dict | None:
    """The chat's saved output for a turn snapshot, with the owner's interactive answers choice.

    None when everything is Auto and interactive answers are off. Read once per turn, so a change
    applies from the next message and a retry keeps the choice it started with.
    """
    _, output = _stored(db, session_id)
    interactive = owner_settings.value_in(db, INTERACTIVE_SETTING, "auto")
    if interactive not in INTERACTIVE:
        interactive = "auto"
    if interactive != "off":
        output = {**output, "interactive": interactive}
    return None if output == AUTO else output


def _answer_models(execution) -> list[str]:
    """Model ids that may answer this turn, as the answer role would pick them."""
    configuration = execution["modelConfiguration"]
    roles = configuration["roleSettings"]
    answer = roles["roles"]["answer"]
    override = execution.get("answerModelId") or (execution.get("configuration") or {}).get(
        "modelId"
    )
    if override:
        return [override]
    if roles["answerMode"] == "manual":
        return [answer["modelId"]] if answer["modelId"] else []
    providers = {item["id"] for item in configuration["providers"] if item["enabled"]}
    models = [
        item["id"]
        for item in configuration["models"]
        if item["enabled"] and item["providerId"] in providers
    ]
    candidates = [identity for identity in answer["eligibleModelIds"] if identity in models]
    if answer["failure"] == "fallback" and answer["fallbackModelId"]:
        candidates.append(answer["fallbackModelId"])
    return candidates


def _hosted_only(execution) -> bool:
    """Whether every model that may answer is hosted. Unknown counts as not hosted."""
    if not execution.get("modelConfiguration"):
        # Without a configuration the router answers ordinary turns on the local model.
        return False
    models = {item["id"]: item for item in execution["modelConfiguration"]["models"]}
    candidates = _answer_models(execution)
    return bool(candidates) and all(
        identity in models and models[identity]["providerId"] in HOSTED_PROVIDERS
        for identity in candidates
    )


def interactive(execution) -> bool:
    """Whether this turn is taught the interactive catalog: On always, Auto with hosted models only.

    Never in a call (the answer is spoken) or when the owner asked for JSON only.
    """
    output = execution.get("output") or {}
    choice = output.get("interactive", "off")
    if choice == "off" or execution.get("callExecution") or output.get("format") == "json":
        return False
    return choice == "on" or _hosted_only(execution)


def messages(execution) -> list[Message]:
    output = execution.get("output")
    if not output:
        return []
    catalog = [Message("system", CATALOG)] if interactive(execution) else []
    parts = []
    if output.get("format", "auto") != "auto":
        parts.append(f"Answer format: {FORMATS[output['format']]}.")
    if output.get("length", "auto") != "auto":
        parts.append(f"Answer length: {LENGTHS[output['length']]}.")
    if output.get("language", "auto") != "auto":
        parts.append(f"Answer language: {output['language']}, unless the owner asks otherwise.")
    if not parts:
        return catalog
    return [*catalog, Message("system", "Owner output settings for this chat. " + " ".join(parts))]


def redact(db, session_ids):
    """Offline forgetting hook: delete this chat's output settings; the caller owns the transaction."""
    for table in ("session_output",):
        if not db.execute("SELECT 1 FROM sqlite_master WHERE name=?", (table,)).fetchone():
            continue
        db.executemany(
            f"DELETE FROM {table} WHERE session_id=?", [(identity,) for identity in session_ids]
        )
